package lesson44;

public class Main {
    public static void main(String[] args) {
        int a = 10;
        double b = 5.5;
        char c = 'A';
        String d = "Salam";
        boolean e = true;

        System.out.println("int a = " + a);
        System.out.println("double b = " + b);
        System.out.println("char c = " + c);
        System.out.println("String d = " + d);
        System.out.println("boolean e = " + e);
    }
}